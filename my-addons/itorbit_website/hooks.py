def _activate_persian(env):
    fa = env.ref('base.lang_fa_IR', raise_if_not_found=False)
    en = env.ref('base.lang_en', raise_if_not_found=False)
    if fa and not fa.active:
        wizard = env['base.language.install'].create({
            'lang_ids': [(6, 0, [fa.id])],
            'overwrite': False,
        })
        wizard.lang_install()
        fa = env.ref('base.lang_fa_IR')
    return fa, en


def _drop_homepage_cow(env):
    cows = env['ir.ui.view'].sudo().search([
        ('key', 'in', [
            'itorbit_website.homepage',
            'itorbit_website.contactus',
            'modir_website.homepage',
            'modir_website.contactus',
            'website.contactus',
            'website.homepage',
        ]),
        ('website_id', '!=', False),
    ])
    if cows:
        cows.unlink()


def _apply_replacements(text, mapping):
    if not text:
        return text
    out = text
    for src, dst in sorted(mapping.items(), key=lambda kv: len(kv[0]), reverse=True):
        out = out.replace(src, dst)
    return out


def _rewrite_view_source(env, key, mapping):
    env.cr.execute(
        "SELECT id, arch_db FROM ir_ui_view WHERE key = %s",
        (key,),
    )
    for view_id, arch_db in env.cr.fetchall():
        if not arch_db or 'en_US' not in arch_db:
            continue
        en = arch_db.get('en_US') or ''
        if not isinstance(en, str):
            continue
        new = _apply_replacements(en, mapping)
        if new != en:
            env.cr.execute(
                """
                UPDATE ir_ui_view
                   SET arch_db = jsonb_set(COALESCE(arch_db, '{}'::jsonb), '{en_US}', to_jsonb(%s::text))
                 WHERE id = %s
                """,
                (new, view_id),
            )


def _translate_views_by_key(env, key, mapping):
    import re
    env.cr.execute(
        "SELECT id, arch_db FROM ir_ui_view WHERE key = %s",
        (key,),
    )
    for view_id, arch_db in env.cr.fetchall():
        if not arch_db or 'en_US' not in arch_db:
            continue
        en = arch_db.get('en_US') or ''
        if not isinstance(en, str):
            continue
        fa = _apply_replacements(en, mapping)
        if key == 'website.footer_custom':
            fa = re.sub(
                r"We are a team of passionate people whose goal is to improve everyone.s life through disruptive products\. We build great products to solve your business problems\.",
                "شرکت دانش‌بنیان مدارگسترش با رتبه یک شورای عالی انفورماتیک و بیش از ۲۰ سال سابقه در پروژه‌های کلان ملی، تولیدکننده پلتفرم‌های بومی نرم‌افزاری است.",
                fa,
                count=1,
            )
        if '\\n' in fa:
            fa = fa.replace('\\n', '\n')
        if arch_db.get('fa_IR') != fa:
            env.cr.execute(
                """
                UPDATE ir_ui_view
                   SET arch_db = jsonb_set(COALESCE(arch_db, '{}'::jsonb), '{fa_IR}', to_jsonb(%s::text))
                 WHERE id = %s
                """,
                (fa, view_id),
            )


def _translate_menus(env):
    import json
    env.cr.execute("SELECT id, name FROM website_menu")
    for menu_id, name in env.cr.fetchall():
        if not name or not isinstance(name, dict):
            continue
        en = name.get('en_US')
        if not en or en not in MENU_FA:
            continue
        if name.get('fa_IR') == MENU_FA[en]:
            continue
        name = dict(name)
        name['fa_IR'] = MENU_FA[en]
        env.cr.execute(
            "UPDATE website_menu SET name = %s::jsonb WHERE id = %s",
            (json.dumps(name, ensure_ascii=False), menu_id),
        )


def _replace_balanced_div(arch, start_marker, new_html):
    start = arch.find(start_marker)
    if start < 0:
        return arch
    i = start
    depth = 0
    while i < len(arch):
        if arch.startswith('<div', i):
            depth += 1
            i = arch.find('>', i)
            if i < 0:
                return arch
            i += 1
            continue
        if arch.startswith('</div>', i):
            depth -= 1
            i += len('</div>')
            if depth == 0:
                return arch[:start] + new_html.strip() + arch[i:]
            continue
        i += 1
    return arch


def _apply_thanks_page(env):
    page = env.ref('website.contactus_thanks', raise_if_not_found=False)
    if not page or not page.view_id:
        return
    view = page.view_id.sudo()
    arch = view.arch_db
    if isinstance(arch, dict):
        en = arch.get('en_US') or next(iter(arch.values()), '')
    else:
        en = arch or ''
    if 'Thank you' not in en or 'ito-thanks' not in en:
        new_en = _replace_balanced_div(en, '<div id="wrap"', THANKS_ARCH)
        if new_en != en:
            view.write({'arch_db': new_en})
    key = view.key or 'website.contactus_thanks'
    _translate_views_by_key(env, key, THANKS_FA)


def _apply_theme(env):
    Assets = env['website.assets'].sudo()
    websites = env['website'].sudo().search([])
    for website in websites:
        assets = Assets.with_context(website_id=website.id)
        assets.make_scss_customization(
            '/website/static/src/scss/options/user_values.scss',
            {
                **ITO_FONTS,
                'color-palettes-name': "'user-palette'",
            },
        )
        assets.make_scss_customization(
            '/website/static/src/scss/options/colors/user_color_palette.scss',
            ITO_PALETTE,
        )


def setup_website(env, *, apply_theme=True):
    """Brand website as مدارگسترش / IT Orbit (separate from Modir.Digital)."""
    fa, en = _activate_persian(env)

    websites = env['website'].sudo().search([])
    for website in websites:
        vals = {'name': 'مدارگسترش'}
        lang_cmds = []
        if en:
            lang_cmds.append((4, en.id))
        if fa:
            lang_cmds.append((4, fa.id))
        if lang_cmds:
            vals['language_ids'] = lang_cmds
            if fa:
                vals['default_lang_id'] = fa.id
        # Persian stays the entry URL. English is chosen from the language switcher (/en).
        vals['auto_redirect_lang'] = False
        website.write(vals)

    company = env.ref('base.main_company', raise_if_not_found=False)
    if company:
        company.write({
            'name': 'مدار گسترش فناوری اطلاعات',
            'email': 'Info@itorbit.net',
            'phone': '021-88373555',
            'website': 'https://www.itorbit.net',
            'primary_color': '#F7931A',
            'secondary_color': '#030304',
        })

    if apply_theme:
        try:
            _apply_theme(env)
        except Exception:
            # Theme SCSS hooks can fail if custom attachments are mid-rebuild;
            # website UI still works from itorbit.scss + primary_variables.
            import logging
            logging.getLogger(__name__).exception('itorbit_website: _apply_theme skipped')
    _drop_homepage_cow(env)
    _apply_thanks_page(env)
    _translate_views_by_key(env, 'itorbit_website.homepage', PAGE_FA)
    _translate_views_by_key(env, 'itorbit_website.contactus', PAGE_FA)
    _rewrite_view_source(env, 'website.footer_custom', FOOTER_EN)
    _translate_views_by_key(env, 'website.footer_custom', FOOTER_FA)
    _translate_menus(env)


def teardown_website(env):
    return
